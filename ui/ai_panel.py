"""
watsonx.ai briefing panel — HospitalFlow AI

Displays the AI-generated situation briefing produced by the Coordinator
Agent's watsonx.ai explanation layer, together with any guardrail warnings.
"""

from __future__ import annotations
import streamlit as st
from agents.ai_guardrails import AIExplanation


_STATUS_TEXT = {
    "not_configured": (
        "watsonx.ai is not configured, so the rule-based summary below is shown instead. "
        "Add `WATSONX_APIKEY` and `WATSONX_PROJECT_ID` to `.env` and restart the app "
        "to enable AI explanations."
    ),
    "disabled": "AI explanations are turned off in the sidebar. Showing rule-based summary only.",
    "withheld": (
        "The watsonx.ai response was withheld because it failed a deterministic safety "
        "check. Showing rule-based summary only."
    ),
}


def render_ai_briefing(ai: AIExplanation) -> None:
    st.markdown("### 🤖 watsonx.ai Situation Briefing")

    if ai.status == "error":
        st.error(
            "watsonx.ai could not be reached, so the rule-based summary below is shown. "
            f"Details: `{ai.error[:300]}`"
        )
        return
    if ai.status in _STATUS_TEXT:
        st.info(_STATUS_TEXT[ai.status])
        _render_warnings(ai)
        return

    if ai.situation_summary:
        st.markdown(ai.situation_summary)

    col_risk, col_watch = st.columns(2)
    if ai.key_risks:
        with col_risk:
            st.markdown("**Key risks**")
            st.markdown("\n".join(f"- {r}" for r in ai.key_risks))
    if ai.watch_next:
        with col_watch:
            st.markdown("**Watch over the next 4 hours**")
            st.markdown("\n".join(f"- {w}" for w in ai.watch_next))

    _render_warnings(ai)
    st.caption(
        f"Generated by IBM watsonx.ai · model `{ai.model_id}` · {ai.latency_s:.1f}s. "
        "AI-generated explanation for decision support only. It does not change "
        "priorities or execute any action. Verify against the rule-based figures."
    )


def _render_warnings(ai: AIExplanation) -> None:
    for w in ai.guardrail_warnings:
        st.warning(f"🛡️ Guardrail: {w}")
